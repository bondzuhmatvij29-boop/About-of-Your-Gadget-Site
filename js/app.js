const root = document.documentElement;
const PAGE = root.getAttribute('data-page') || 'html5';
const STYLES_BY_PAGE = { html5: ['aero', 'm3', 'holo'], html4: ['aero', 'holo'] };

function applyLang(lang) {
  const dict = T[lang] || T.en;
  root.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => { const v = dict[el.dataset.i18n]; if (v !== undefined) el.textContent = v; });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { const v = dict[el.dataset.i18nHtml]; if (v !== undefined) el.innerHTML = v; });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    const [attr, key] = el.dataset.i18nAttr.split(':');
    if (dict[key] !== undefined) el.setAttribute(attr, dict[key]);
  });
  const sel = document.getElementById('langSel');
  if (sel) sel.value = lang;
  try { localStorage.setItem('aog-lang', lang); } catch (e) {}
}

function detectLang() {
  let saved = null;
  try { saved = localStorage.getItem('aog-lang'); } catch (e) {}
  if (saved && T[saved]) return saved;
  const langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en'];
  for (const l of langs) {
    const code = String(l).slice(0, 2).toLowerCase();
    if (code === 'uk' || code === 'ru' || code === 'en') return code;
  }
  return 'en';
}

// Design style. Saved only when the visitor picks it, so a page that cannot show
// a style (Material 3 on HTML 4) falls back to Aero without losing the choice.
function applyStyle(style, save) {
  const allowed = STYLES_BY_PAGE[PAGE] || STYLES_BY_PAGE.html5;
  const used = allowed.indexOf(style) === -1 ? 'aero' : style;
  root.setAttribute('data-style', used);
  document.querySelectorAll('[data-style-value]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.styleValue === used)));
  if (save) try { localStorage.setItem('aog-style', style); } catch (e) {}
}

// App theme. "system" follows the phone's dark-mode setting as the browser reports it.
let themePref = 'black';
function resolveTheme(t) {
  if (t === 'system') return (window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches) ? 'black' : 'white';
  return t;
}
function applyTheme(t, save) {
  themePref = t;
  root.setAttribute('data-theme', resolveTheme(t));
  document.querySelectorAll('[data-theme-value]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.themeValue === t)));
  if (save) try { localStorage.setItem('aog-theme', t); } catch (e) {}
}
if (window.matchMedia) {
  const dark = window.matchMedia('(prefers-color-scheme: dark)');
  const onChange = () => { if (themePref === 'system') applyTheme('system', false); };
  if (dark.addEventListener) dark.addEventListener('change', onChange); else if (dark.addListener) dark.addListener(onChange);
}

// Settings controls (settings.html and the HTML 4 page)
document.querySelectorAll('[data-style-value]').forEach(b => b.addEventListener('click', () => applyStyle(b.dataset.styleValue, true)));
document.querySelectorAll('[data-theme-value]').forEach(b => b.addEventListener('click', () => applyTheme(b.dataset.themeValue, true)));
const langSel = document.getElementById('langSel');
if (langSel) langSel.addEventListener('change', e => applyLang(e.target.value));

// Overflow menu (index.html)
const menu = document.getElementById('menu');
const menuBtn = document.getElementById('menuBtn');
if (menu && menuBtn) {
  menuBtn.addEventListener('click', e => {
    e.stopPropagation();
    const open = menu.classList.toggle('open');
    menuBtn.setAttribute('aria-expanded', String(open));
  });
  document.addEventListener('click', e => { if (!e.target.closest('.menu-wrap')) menu.classList.remove('open'); });
  menu.querySelectorAll('a').forEach(a => a.addEventListener('click', () => menu.classList.remove('open')));
}

// Live clock (index.html)
const clock = document.getElementById('clock');
if (clock) {
  const tick = () => { clock.textContent = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }); };
  tick(); setInterval(tick, 30000);
}

// Restore saved choices. Defaults: Aero, Black theme, language from the browser.
let savedStyle = null, savedTheme = null;
try { savedStyle = localStorage.getItem('aog-style'); savedTheme = localStorage.getItem('aog-theme'); } catch (e) {}
applyStyle(savedStyle || 'aero', false);
applyTheme(['white', 'black', 'system'].includes(savedTheme) ? savedTheme : 'black', false);
applyLang(detectLang());
